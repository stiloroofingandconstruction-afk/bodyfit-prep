/**
 * Base de datos local de alimentos.
 * Todos los macros son POR 100 g (o 100 ml cuando unit === 'ml').
 *
 * Formato compacto: f(id, nombre, categoria, rol, [kcal, prot, carb, grasa, fibra], alias, extra)
 */
import type { Food, FoodCategory, FoodRole, ServingSize } from '@/domain/types';

type Tuple = [kcal: number, protein: number, carbs: number, fat: number, fiber: number];

interface Extra {
  brand?: string;
  unit?: 'g' | 'ml';
  servings?: ServingSize[];
  state?: 'crudo' | 'cocido';
}

function f(
  id: string,
  name: string,
  category: FoodCategory,
  role: FoodRole,
  [kcal, protein, carbs, fat, fiber]: Tuple,
  aliases: string[] = [],
  extra: Extra = {},
): Food {
  return {
    id,
    name,
    category,
    role,
    aliases,
    per100: { kcal, protein, carbs, fat, fiber },
    unit: extra.unit ?? 'g',
    ...(extra.brand ? { brand: extra.brand } : {}),
    ...(extra.servings ? { servings: extra.servings } : {}),
    ...(extra.state ? { state: extra.state } : {}),
  };
}

